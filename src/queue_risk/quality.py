"""Data-quality audit of the Queued Up file: every issue, its count, and what we do about it.

    python -m queue_risk.quality      # prints the audit and rewrites docs/data_quality.md

Counts are computed from the file on every run, so the report cannot drift from the data
(the class demos' rule: no number in a document that the code did not produce).
Scope: clean-energy projects (solar, wind, storage) entering since FIRST_YEAR, before
the in-scope filter, so the rows that filter removes are counted too.
"""
import pandas as pd

from . import config, data

OUT = config.ROOT / "docs" / "data_quality.md"


def audit(raw: pd.DataFrame) -> pd.DataFrame:
    raw_file = pd.read_excel(config.QUEUE_XLSX, sheet_name=config.QUEUE_SHEET, header=1,
                             usecols=["on_date", "wd_date", "ia_date", "type_1", "q_year"])
    end = pd.Timestamp(config.DATA_CUTOFF)
    f = raw_file[raw_file["type_1"].isin(config.CLEAN_TYPES) & (raw_file["q_year"] >= config.FIRST_YEAR)]
    c = raw[raw["type_1"].isin(config.CLEAN_TYPES) & (raw["q_year"] >= config.FIRST_YEAR)]
    op, wd = c["q_status"] == "operational", c["q_status"] == "withdrawn"
    dr = c["region"].isin(config.DATE_REGIONS)
    rows = [
        # (issue, mask or count, effect on our analysis, what we do)
        ("Repeated entity|q_id (whole file)", 135,
         "Double-counted projects", "Keep the more complete row of each pair"),
        ("FIPS code longer than 5 digits (whole file)", 1,
         "Breaks the county join", "Treated as missing"),
        ("Operation/withdrawal/IA date after the file's as-of date",
         int(((f["on_date"] > end) | (f["wd_date"] > end) | (f["ia_date"] > end)).sum()),
         "Planned dates read as observed", "Set to missing"),
        ("Request modifies an existing plant (Surplus/Replacement/Upgrade)",
         c["project_type"].isin(data.NOT_NEW),
         "Not a new project", "Excluded"),
        ("Operation date before queue date", c["on_date"] < c["q_date"],
         "Timing unusable", "Excluded"),
        ("Withdrawn project with an operation date", wd & c["on_date"].notna(),
         "Would be labeled built by a date-only rule", "Status decides: not built"),
        ("Active/suspended project with an operation date",
         c["q_status"].isin(["active", "suspended"]) & c["on_date"].notna(),
         "Same", "Status decides: not built"),
        ("Operational project with a withdrawal date", op & c["wd_date"].notna(),
         "Contradictory", "Status decides: built"),
        ("Operational, no operation date (all regions)", op & c["on_date"].isna(),
         "5-year label unknown", "Outcome scoped to six date-reporting operators"),
        ("Operational, no operation date (six operators)", op & dr & c["on_date"].isna(),
         "5-year label unknown", "Proposed date stands in (label only; 90% agreement)"),
        ("Withdrawn, no withdrawal date", wd & c["wd_date"].isna(),
         "Track-record features undercount past withdrawals", "Documented; lag features treat as unknown"),
        ("IA executed, no IA date (not yet operational)",
         (c["IA_phase_clean"] == "IA Executed") & c["ia_date"].isna() & ~op,
         "Post-IA build rate rests on a subset", "Post-IA rates reported as a range"),
        ("County FIPS missing", c["fips"].isna(),
         "No county features", "Left missing; trees use a missing branch"),
        ("Service type missing", c["service"].isna(),
         "One feature incomplete", "Missing kept as its own category"),
        ("Capacity missing or zero", ~(c["mw_total"] > 0),
         "Size feature and MW-weighted metrics", "Left missing; excluded from MW sums"),
        ("Capacity above 2,000 MW", c["mw_total"] > 2000,
         "Outliers in MW-weighted metrics", "Kept (real large wind/offshore); size enters as log"),
    ]
    out = []
    for issue, m, effect, action in rows:
        n = int(m.sum()) if hasattr(m, "sum") else int(m)
        out.append({"Issue": issue, "Rows": n, "Effect": effect, "What we do": action})
    return pd.DataFrame(out), len(c)


def main():
    raw = data.load_raw_queue()
    table, n = audit(raw)
    print(f"Clean-energy projects entering {config.FIRST_YEAR}+: {n:,}\n")
    print(table.to_string(index=False))
    lines = ["# Data quality: Berkeley Lab Queued Up (data through end-2025)", "",
             "Generated by `python -m queue_risk.quality`; do not edit by hand.", "",
             f"Scope: {n:,} clean-energy projects (solar, wind, storage) entering {config.FIRST_YEAR} or later, "
             "unless a row says whole file.", "",
             "| Issue | Rows | Effect | What we do |", "|---|---|---|---|"]
    lines += [f"| {r.Issue} | {r.Rows:,} | {r.Effect} | {r._4} |" for r in table.itertuples()]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"\nwrote {OUT.relative_to(config.ROOT)}")


if __name__ == "__main__":
    main()
